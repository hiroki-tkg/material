"""すべての部品を使った見本の資料。テーマを変えて動かすと、AP／AF／ハナイチの配色の違いが分かる。

    python3 example_deck.py hanaichi out/example_hanaichi.pptx
    bash render.sh out/example_hanaichi.pptx "見本" "2026.10 株式会社DOMUZ"

数字はすべて架空。実際の資料では data_*.py に数字をまとめ、文章は f-string で数字から組み立てる。
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deck_lib import *  # noqa: E402,F401

theme = sys.argv[1] if len(sys.argv) > 1 else "domuz"
out = sys.argv[2] if len(sys.argv) > 2 else f"example_{theme}.pptx"
use_theme(theme)
NAME = {"ap": "アンドプランツ", "af": "アンドフラワー", "hanaichi": "ハナイチ", "domuz": "事業A"}[T.name]

# ---- 架空のデータ（百万円・税抜）
FY = ["24年9月期", "25年9月期", "26年9月期"]
S = [12.1, 30.4, 46.8]
GP = [4.8, 9.2, 15.1]
AD = [0.0, 7.8, 8.1]
NET = [g - a for g, a in zip(GP, AD)]
Q_LABELS = ["24年\n10〜12月", "25年\n1〜3月", "4〜6月", "7〜9月", "10〜12月", "26年\n1〜3月", "4〜6月", "7〜9月"]
Q_S = [4.0, 8.7, 10.1, 7.6, 7.4, 13.8, 12.3, 15.7]
Q_AD = [0.2, 1.4, 4.2, 2.0, 1.8, 1.6, 1.2, 3.5]

# 1. 表紙
cover("社内向け資料", [NAME, "事業エコノミクスの整理とまとめ"], "売上・限界利益・広告費の推移と、今後のエコノミクス",
      ["2026年10月", "株式会社DOMUZ", "担当者名"])

# 2. 構成
agenda("本資料の構成", [
    ("1", "エコノミクスの整理と経年推移", "24年9月期〜26年9月期の売上・限界利益・広告費"),
    ("2", "今後の事業におけるエコノミクスの整理", "原価・ROAS・直接固定費、LTV/CAC、損益分岐の月商"),
    ("3", "中長期の可能性", "新しいサービスと事業間の連携"),
], note="※ 用語と集計の前提は最終ページにまとめています")

# 3. 要約（数字が出そろってから書く。ここでは先に置く）
summary = content_slide(NAME)
draw_claims(summary, [
    ("1", "売上は3期で拡大、限界利益率は30%台を維持", [
        f"売上は{S[0]:.0f} → {S[1]:.0f} → {S[2]:.0f}百万円（24年9月期は8か月）",
        f"限界利益率は{GP[1] / S[1] * 100:.0f} → {GP[2] / S[2] * 100:.0f}%。広告費込み限界利益は{NET[1]:.1f} → {NET[2]:.1f}百万円"]),
    ("2", "広告は新規獲得に集中。1人あたりの採算はセグメントで差がある", [
        "CAC 4,672円に対し、12か月の限界利益LTV 1,259円（LTV/CAC 0.3倍）",
        "セグメント別にCACを上回るのは販売（1.1倍）だけ"]),
    ("3", "収益化の鍵はリピート顧客の積み上げと広告費込み限界利益率の改善", [
        "売上の77%は2回目以降の注文。直接固定費は月0.52百万円と小さい"]),
])
footnote(summary, "※ 数値は税抜。用語の定義と集計の前提は最終ページ")

# 4. 章扉
divider("01", "ECONOMICS TREND", f"{NAME}のエコノミクスの推移", "24年9月期 〜 26年9月期")

# 5. 四半期の棒グラフ＋期別の表
s = content_slide(f"{NAME}：四半期の売上と期別の限界利益")
message(s, f"売上は{S[1]:.0f} → {S[2]:.0f}百万円（+{(S[2] / S[1] - 1) * 100:.0f}%）、限界利益率{GP[2] / S[2] * 100:.0f}%")
text(s, 214, 154, 600, 24, "四半期の売上　単位：百万円", size=14, color=SECONDARY)
legend(s, 820, 154, [(NAME, T.accent)])
bar_chart(s, 200, 180, 720, 300, Q_LABELS, [("売上", Q_S)], ticks=(0, 5, 10, 15), value_labels=True)
kpi_table(s, 56, 520, 1016, ["", *FY], [
    ["売上", *[f"{v:.1f}" for v in S]],
    ["限界利益", *[f"{v:.1f}" for v in GP]],
    ["限界利益率", *[f"{g / v * 100:.1f}%" for g, v in zip(GP, S)]],
], col_w=[556, 150, 150, 160], bold_rows=(2,))
footnote(s, "※ 税抜。24年9月期は2024年2月〜9月の8か月")

# 6. 広告投資（棒＋線）
s = content_slide("広告投資：新規獲得に広告を投下", "四半期の売上・広告費・ROAS　単位：百万円")
legend(s, 214, 154, [("売上", PALE), ("広告費", T.accent)])
legend(s, 420, 154, [("ROAS（右軸）", T.dark)], line=True)
# 棒は vmax を広げて上1/3を空け、ROAS の線はその帯（右軸 0〜1200%）に収める
ax = bar_chart(s, 200, 180, 720, 330, Q_LABELS, [("売上", Q_S), ("広告費", Q_AD)], colors=[PALE, T.accent],
               vmax=24, ticks=(0, 5, 10, 15), value_labels=True)
roas = [s_ / a_ * 100 for s_, a_ in zip(Q_S, Q_AD)]
ry = ax.yv2(1200)
L0 = 1  # 広告費が小さい最初の四半期は線から外す
polyline(s, [(ax.x(i), ry(roas[i])) for i in range(L0, len(roas))], T.dark, 2.0)
for i in (L0, len(roas) - 1):
    text(s, ax.x(i) - 30, ry(roas[i]) - 22, 60, 16, f"{roas[i]:.0f}%", size=10, bold=True, color=T.dark, align=PP_ALIGN.CENTER, en=True)
text(s, 56, 560, 1016, 60, ["26年7月〜 広告費を増やし、ROASは下がった。", "広告効率と限界利益率の両方で損益が決まる"],
     size=18, bold=True, spacing=1.5)
footnote(s, "※ ROAS＝売上÷広告費。24年10〜12月は広告費が小さいためROASの線は25年1〜3月から")

# 7. ウォーターフォール（2本並べる）
divider("02", "UNIT ECONOMICS", "今後の事業におけるエコノミクスの整理", "原価・広告・直接固定費と、損益分岐")
s = content_slide("エコノミクス：直近の四半期と通年", "棒の数字は売上を100としたときの割合（%）　※税抜")
waterfall(s, 70, "26年7〜9月", [("原価等", 11.07), ("広告費", 3.47), ("発送\n人件費", 0.99), ("拠点費", 0.56)],
          "貢献\n利益", -0.42, 15.67)
waterfall(s, 600, "26年9月期（通年）", [("原価等", 31.75), ("広告費", 8.14), ("発送\n人件費", 3.96), ("拠点費", 2.26)],
          "貢献\n利益", 0.71, 46.82)
footnote(s, "※ 原価等＝商品原価・送料・資材・決済手数料。直接固定費＝発送人件費＋拠点費")

# 8. ランキング（横棒＋基準線）と大きな数字
s = content_slide("LTV/CAC：成り立つセグメント", "LTV＝26年9月期の顧客1人あたりの年間限界利益。CAC 4,672円で共通　※税抜")
x, w = 56, 470
rect(s, x, 150, w, 6, T.accent)
text(s, x, 172, w, 34, "新規顧客1人あたりの採算", size=21, bold=True)
big_number(s, x, 214, "LTV/CAC（限界利益ベース）", "0.3", "倍", color=STRONG)
big_number(s, x + 236, 214, "売上ベース", "1.6", "倍", color=SECONDARY, size=30)
kpi_table(s, x, 334, w, ["", "25年9月期", "26年9月期"], [
    ["CAC（広告費÷新規顧客数）", "10,398円", "4,672円"], ["初回の購入単価", "4,479円", "6,166円"],
    ["12か月の限界利益（LTV）", "1,259円", "—"]], col_w=[w - 240, 120, 120], bold_rows=(0, 2))
vline(s, 548, 150, 540)
x2, w2 = 568, 504
rect(s, x2, 150, w2, 6, MOSS)
text(s, x2, 172, w2, 34, "セグメント別の採算（高い順）", size=21, bold=True)
ranked_bars(s, x2, 246, w2, [
    ("販売", 1.12, ["75", "5,235円"]), ("レッスン・お稽古", 0.63, ["116", "2,951円"]), ("装花", 0.42, ["169", "1,972円"]),
    ("撮影装飾", 0.36, ["117", "1,693円"]), ("趣味", 0.30, ["254", "1,392円"]), ("自宅鑑賞用・ギフト", 0.20, ["906", "925円"]),
], ref=1.0, cols=("新規", "年間限界利益"))
text(s, 56, 694, 1016, 60, ["CACを上回るのは販売（1.1倍）だけ。新規の半分を占める自宅鑑賞用・ギフトは0.2倍。",
                            "広告は事業者セグメントに寄せ、個人向けはオーガニック中心にする"], size=16, bold=True, spacing=1.45)
footnote(s, "※ 顧客単位で集計。CACは広告費をすべて新規獲得にかかったとみなした値で、セグメント別には分けられないため共通")

# 9. 用語
terms_page("用語と集計の前提", [
    ("期", "9月決算。「26年9月期」＝2025年10月〜2026年9月"),
    ("売上", "税抜・注文日ベースの純売上（確定請求額−返金）。キャンセル・テスト注文は除く"),
    ("限界利益", "売上 − 商品原価・送料・資材・決済手数料"),
    ("広告費", "Google・Meta・Yahoo! などの広告費（税抜）"),
    ("広告費込み限界利益", "限界利益 − 広告費"),
    ("直接固定費", "発送人件費＋拠点費。本社の人件費・共通費は含まない"),
    ("LTV／CAC", "LTV＝顧客1人あたりの12か月の限界利益。CAC＝広告費÷新規顧客数"),
    ("出典", "管理画面（売上・限界利益）、Marketing Master（広告費）、受注データ（顧客単位）"),
])

os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
save(out)
